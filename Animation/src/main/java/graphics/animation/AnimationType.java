package graphics.animation;

/**
 * Enum representing different types of animations.
 */
public enum AnimationType {
    /**
     * Animation for a bouncing ball.
     */
    BOUNCING_BALL,

    /**
     * Animation for a rolling ball.
     */
    ROLLING_BALL,

    /**
     * Animation for a colliding ball.
     */
    COLLIDING_BALL,

    /**
     * Animation for a draggable ball.
     */
    DRAGGABLE_BALL,

    /**
     * Animation for a zooming ball in X Axis.
     */
    ZOOMING_BALL_X,

    /**
     * Animation for a zooming ball in Y Axis.
     */
    ZOOMING_BALL_Y,

    /**
     * Animation for a zooming ball in Z Axis.
     */
    ZOOMING_BALL,

    /**
     * Animation for filling a bucket.
     */
    FILLING_BUCKET,
}

